-- ============================================================
-- الترحيل 38: جدول ملفات الأرشيف — الداتا بيز مصدر الحقيقة للمزج
-- ============================================================
-- المشكلة المكتشفة أثناء الاختبار: عملية "قراءة ثم دمج ثم كتابة" على
-- ملفات Supabase Storage (S3) غير آمنة بسبب التناسق المؤجل (eventual
-- consistency) عند الكتابة فوق ملف موجود — فالقراءة بعد الكتابة قد تُرجع
-- نسخة قديمة من الملف، فيفقد المحتوى المدمج المكتوب للتو.
--
-- الحل: جدول archive_month_files يخزّن محتوى ملف كل شهر (jsonb) ويكون
-- مصدر الحقيقة للمزج (قراءة/كتابة فورية متسقة)، بينما يبقى ملف التخزين
-- نسخة طبقية خارجية (mirror) للنسخ الاحتياطي والدوران فقط. أي فشل في
-- رفع النسخة الطبقية لا يمنع الحفظ في الداتا بيز، لكن فشل الحفظ في
-- الداتا بيز يُوقف العملية (ضمانة التسليم قبل الحذف).
-- ============================================================

CREATE TABLE IF NOT EXISTS archive_month_files (
  month_key text PRIMARY KEY,          -- صيغة YYYY-MM
  content jsonb NOT NULL,              -- { children: [...], batches: [...] }
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- وصول حصري عبر service_role (يتم تمكين RLS دون سياسات)
ALTER TABLE archive_month_files ENABLE ROW LEVEL SECURITY;
