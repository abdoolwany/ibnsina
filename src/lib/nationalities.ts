/** رمز خاص في فلتر الجنسية يعني "غير مصري" (أي قيمة لا تبدأ بـ "مصر") */
export const NON_EGYPTIAN_TOKEN = '__NON_EGYPTIAN__'

/** قائمة الجنسيات مرتبة أبجديًا (عربي) */
export const NATIONALITIES: string[] = [...RAW_NATIONALITIES].sort((a, b) => a.localeCompare(b, 'ar'))

/** هل القيمة "مصرية"؟ (مصر، مصري، مصرية... كلها مصرية) */
export function isEgyptianNationality(value: string | null | undefined): boolean {
  if (!value) return false
  const norm = value.replace(/[أإآ]/g, 'ا').replace(/ة$/g, 'ه').toLowerCase().trim()
  return norm.startsWith('مصر')
}

/**
 * تحويل اختيار الجنسية من الواجهة إلى معامل RPC:
 * - null / '' / الكل → null (بدون فلترة)
 * - غير مصري → NON_EGYPTIAN_TOKEN
 * - "مصر" (الخيار الثابت) → "مصر" (بادئة تطابق "مصري"/"مصرية" المخزنة في قاعدة البيانات)
 * - أي جنسية محددة → اسمها كما هو
 */
export function nationalityToFilterParam(value: string | null | undefined): string | null {
  if (!value || value === 'all') return null
  if (value === 'non_egyptian') return NON_EGYPTIAN_TOKEN
  if (value === 'egyptian') return 'مصر'
  return value
}
